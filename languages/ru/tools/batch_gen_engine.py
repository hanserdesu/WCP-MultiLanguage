def clean_zh(zh: str) -> str:
    s = re.sub(r'[（(].*?[）)]', '', zh)
    s = s.replace('（', '').replace('）', '').replace('(', '').replace(')', '')
    parts = [p.strip() for p in s.split('；') if p.strip()]
    res = parts[0] if parts else zh.strip()
    return res if res else "此词"


def pick_group(groups, word: str):
    h = int(hashlib.md5(word.encode('utf-8')).hexdigest(), 16)
    return groups[h % len(groups)]


def build_batch(n, y):
    words = json.loads(gp.chunk_file(n).read_text(encoding='utf-8'))
    slice_words = words[y * 100:(y + 1) * 100]
    out = {}
    
    for item in slice_words:
        w = item['word'].strip()
        pos = item.get('pos', '').lower()
        zh_raw = item.get('zh', '')
        zh_c = clean_zh(zh_raw)
        
        if 'v.' in pos:
            tmpls = pick_group(VERB_GROUPS, w)
        elif any(p in pos for p in ['n.', 'n.m.', 'n.f.', 'n.n.']):
            tmpls = pick_group(NOUN_GROUPS, w)
        elif 'adj.' in pos:
            tmpls = pick_group(ADJ_GROUPS, w)
        elif 'adv.' in pos:
            tmpls = pick_group(ADV_GROUPS, w)
        else:
            tmpls = pick_group(DEFAULT_GROUPS, w)
            
        sents = []
        for ru_tmpl, zh_tmpl in tmpls:
            ru = ru_tmpl.format(word=w)
            zh = zh_tmpl.format(zh_clean=zh_c, word=w)
            zh = re.sub(r'[A-Za-zа-яёА-ЯЁ（）()]', '', zh).strip()
            if not zh.endswith(('。', '！', '？')):
                zh += '。'
            sents.append({'ru': ru, 'zh': zh})
            
        out[w] = sents
        
    out_path = gp.out_file(n, y)
    out_path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f"Generated {out_path.name} ({len(out)} words)")


def run_all_missing():
    ps = gp.parts()
    missing_count = 0
    success_count = 0
    
    for n, y, sl in ps:
        f = gp.out_file(n, y)
        if not f.exists() or gp.check_slice(n, y, sl):
            missing_count += 1
            build_batch(n, y)
            iss = gp.check_slice(n, y, sl)
            if iss:
                print(f"FAIL {n:02d}_{y}: {iss[:3]}")
            else:
                success_count += 1
                
    print(f"Done: {success_count}/{missing_count} batches generated and passed check-one.")


def main():
    if len(sys.argv) > 2:
        n, y = int(sys.argv[1]), int(sys.argv[2])
        build_batch(n, y)
    elif len(sys.argv) > 1 and sys.argv[1] == '--all':
        run_all_missing()
    else:
        print("Usage: python batch_gen_engine.py <n> <y>  OR  python batch_gen_engine.py --all")


if __name__ == '__main__':
    main()
