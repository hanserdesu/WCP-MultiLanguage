def apply_stress_patch():
    p = Path('D:/ATooManyLanguage/Russian/output/russian_books.json')
    data = json.loads(p.read_text(encoding='utf-8'))
    patched = 0
    for lv, words in data['levels'].items():
        for w in words:
            word = w['word']
            if word in STRESS_PATCH and not w.get('stress'):
                w['stress'] = STRESS_PATCH[word]
                patched += 1
    p.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'Successfully patched {patched} multi-syllable words in russian_books.json')

if __name__ == '__main__':
    apply_stress_patch()
