def main():
    src = json.loads((ROOT / 'work' / 'cur_26.json').read_text(encoding='utf-8'))
    words = [w['word'] for w in src]
    kept, drop = [], []
    for w in words:
        val = CUR_26_DATA.get(w)
        if not val:
            print(f"MISSING: {w}")
            continue
        if val[0] == "-":
            drop.append({"word": w, "reason": val[1].replace("drop:", "")})
        else:
            kept.append({"word": w, "zh": val[0], "level": val[1]})
            
    print(f"Kept: {len(kept)}, Drop: {len(drop)}, Total: {len(kept) + len(drop)} / {len(words)}")
    out_file = ROOT / 'work' / 'cur_out_26.json'
    out_file.write_text(json.dumps({"kept": kept, "drop": drop}, ensure_ascii=False, indent=1), encoding='utf-8')
    print("Written to", out_file)
    
    r = subprocess.run([sys.executable, str(ROOT / 'tools' / 'curate_pipeline.py'), 'check-one', '26'],
                       capture_output=True, text=True, encoding='utf-8')
    print(r.stdout)
    if r.returncode != 0:
        print("STDERR:", r.stderr)
        sys.exit(1)

if __name__ == '__main__':
    main()
