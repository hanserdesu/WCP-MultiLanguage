def main():
    src = json.loads((ROOT / 'work' / 'cur_07.json').read_text(encoding='utf-8'))
    words = [w['word'] for w in src]
    
    kept = []
    drop = []
    
    for w in words:
        if w not in CUR_07_DATA:
            # 自动分类处理
            pass
        val = CUR_07_DATA.get(w)
        if not val:
            print(f"MISSING: {w}")
            continue
        if val[0] == "-":
            drop.append({"word": w, "reason": val[1].replace("drop:", "")})
        else:
            kept.append({"word": w, "zh": val[0], "level": val[1]})
            
    print(f"Kept: {len(kept)}, Drop: {len(drop)}, Total: {len(kept) + len(drop)} / {len(words)}")
    out_file = ROOT / 'work' / 'cur_out_07.json'
    out_file.write_text(json.dumps({"kept": kept, "drop": drop}, ensure_ascii=False, indent=1), encoding='utf-8')
    print("Written to", out_file)
    
    r = subprocess.run([sys.executable, str(ROOT / 'tools' / 'curate_pipeline.py'), 'check-one', '07'],
                       capture_output=True, text=True, encoding='utf-8')
    print(r.stdout)
    if r.returncode != 0:
        print("STDERR:", r.stderr)
        sys.exit(1)

if __name__ == '__main__':
    main()
