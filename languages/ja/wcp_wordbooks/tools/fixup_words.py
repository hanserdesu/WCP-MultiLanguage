# 词字段尾部括号注记: じゅうたん（カーペット） -> じゅうたん
PAREN_TAIL = re.compile(r'（[^（）]*）$|\([^()]*\)$')


def fix_word(w):
    w = w.strip()
    if w in WORD_FIX:
        return WORD_FIX[w]
    fixed = PAREN_TAIL.sub('', w).strip()
    return fixed or w


def load_supplements():
    """supplement_*.json: [{'word','reading','meaning_en','level'}]"""
    sups = {}
    for p in sorted(DATA.glob('supplement_*.json')):
        rows = json.loads(p.read_text(encoding='utf-8'))
        n = 0
        for r in rows:
            lv = r.get('level', '').lower()
            if lv not in ('n5', 'n4', 'n3', 'n2', 'n1'):
                continue
            sups.setdefault(lv, []).append({
                'word': r['word'].strip(),
                'reading': r.get('reading', '').strip(),
                'meaning_en': r.get('meaning_en', '').strip(),
                'example_ja': r.get('example_ja', ''),
                'example_en': '',
                'level': lv.upper(),
            })
            n += 1
        print(f'  {p.name}: {n} 条')
    return sups


def main():
    data = json.loads((OUT / 'jlpt_books.json').read_text(encoding='utf-8'))
    fixed = dropped = added = 0

    for lv, rows in data['levels'].items():
        for r in rows:
            w2 = fix_word(r['word'])
            if w2 != r['word']:
                r['word'] = w2
                fixed += 1
        # 级别内去重
        seen, dedup = set(), []
        for r in rows:
            if r['word'] in seen:
                dropped += 1
                continue
            seen.add(r['word'])
            dedup.append(r)
        data['levels'][lv] = dedup

    # 并入补充词
    sups = load_supplements()
    if sups:
        for lv, rows in sups.items():
            existing = {r['word'] for r in data['levels'][lv]}
            # 全库已有词(避免低级别撞高级别)
            all_w = {r['word'] for rows2 in data['levels'].values()
                     for r in rows2}
            for r in rows:
                if r['word'] in all_w:
                    continue
                data['levels'][lv].append(r)
                existing.add(r['word'])
                all_w.add(r['word'])
                added += 1

    total = {lv: len(rows) for lv, rows in data['levels'].items()}
    (OUT / 'jlpt_books.json').write_text(
        json.dumps(data, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f'修正词字段 {fixed} 个, 去重删除 {dropped} 条, 新增补充词 {added} 个')
    print(f'各级别词数: {json.dumps(total, ensure_ascii=False)}')


if __name__ == '__main__':
    main()
